const LANGS = ['fr', 'ar', 'en'];
const norm = (s) => s.replace(/\s+/g, ' ').trim();
let lang = 'fr';
try { lang = localStorage.getItem('sahbi-lang') || ''; } catch { /* ignorato */ }
if (!LANGS.includes(lang)) {
  const nav = (navigator.languages || [navigator.language || 'fr']).map((l) => String(l).toLowerCase());
  lang = nav.find((l) => l.startsWith('ar')) ? 'ar' : nav[0]?.startsWith('fr') ? 'fr' : nav[0]?.startsWith('en') ? 'en' : 'fr';
}
const col = LANGS.indexOf(lang);
const MAP = new Map();
if (col > 0) for (const row of D) MAP.set(norm(row[0]), row[col]);

const fill = (s, p) => (p ? s.replace(/\{(\w+)\}/g, (m, k) => (p[k] ?? m)) : s);
// tr('testo francese', { x: ... }) → testo nella lingua scelta (o francese se manca la traduzione).
function tr(s, p) {
  if (typeof s !== 'string') return s;
  if (col > 0) {
    const m = s.match(/^(\s*)([\s\S]*?)(\s*)$/);
    const hit = MAP.get(norm(m[2]));
    if (hit != null) return fill(m[1] + hit + m[3], p);
  }
  return fill(s, p);
}

const ATTRS = ['placeholder', 'aria-label', 'title', 'alt', 'data-p'];
const skip = (n) => { const e = n.nodeType === 1 ? n : n.parentElement; return !e || !!e.closest('[data-noi18n],script,style,textarea'); };
function doText(n) {
  if (skip(n)) return;
  const v = n.data; if (!v.trim()) return;
  const m = v.match(/^(\s*)([\s\S]*?)(\s*)$/);
  const hit = MAP.get(norm(m[2]));
  if (hit != null && hit !== m[2]) n.data = m[1] + hit + m[3];
}
function doAttrs(e) {
  if (e.closest('[data-noi18n]')) return;
  for (const a of ATTRS) { const v = e.getAttribute(a); if (v) { const hit = MAP.get(norm(v)); if (hit != null && hit !== v) e.setAttribute(a, a === 'data-p' ? v.replace(norm(v), hit) : hit); } }
}
function walk(root) {
  if (root.nodeType === 3) { doText(root); return; }
  if (root.nodeType !== 1) return;
  doAttrs(root);
  const it = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = it.nextNode(); n; n = it.nextNode()) n.nodeType === 3 ? doText(n) : doAttrs(n);
}

const LOCALE = { fr: 'fr-FR', ar: 'ar-u-nu-latn', en: 'en-GB' }[lang];
function start() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  if (col === 0) return;
  walk(document.body);
  new MutationObserver((list) => {
    for (const r of list) {
      if (r.type === 'characterData') doText(r.target);
      else if (r.type === 'attributes') doAttrs(r.target);
      else for (const n of r.addedNodes) walk(n);
    }
  }).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
